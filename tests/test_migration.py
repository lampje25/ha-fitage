@pytest.mark.asyncio
async def test_current_minor_version_is_clean_noop() -> None:
    """A clean v1.3 config entry does not access or mutate the registry."""
    entry = _config_entry()
    entry.minor_version = 2

    assert await async_migrate_entry(SimpleNamespace(), entry)
    assert entry.minor_version == 2


@pytest.mark.asyncio
async def test_config_entry_migration_runs_before_setup_and_bumps_minor_version(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Successful registry migration advances config entry version 1.1 to 1.2."""
    registry = FakeRegistry(
        [FakeRegistryEntry("sensor.weight", "entry-1_weight_primary-id")]
    )
    entry = _config_entry()

    class ConfigEntries:
        @staticmethod
        def async_update_entry(
            entry_to_update: SimpleNamespace, **changes: object
        ) -> None:
            for key, value in changes.items():
                setattr(entry_to_update, key, value)

    hass = SimpleNamespace(config_entries=ConfigEntries())
    monkeypatch.setattr(
        "custom_components.fitage.er.async_get", lambda unused_hass: registry
    )
    monkeypatch.setattr(
        "custom_components.fitage.er.async_entries_for_config_entry",
        lambda unused_registry, unused_entry_id: registry.entries.copy(),
    )

    assert await async_migrate_entry(hass, entry)
    assert entry.version == 1
    assert entry.minor_version == 2
    assert registry.entries[0].unique_id == "primary-id_profile_weight"


@pytest.mark.asyncio
async def test_config_entry_collision_does_not_advance_version(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """A collision blocks setup and leaves the migration retryable."""
    registry = FakeRegistry(
        [
            FakeRegistryEntry("sensor.old", "entry-1_weight_primary-id"),
            FakeRegistryEntry("sensor.new", "primary-id_profile_weight"),
        ]
    )
    entry = _config_entry()
    hass = SimpleNamespace(config_entries=SimpleNamespace())
    monkeypatch.setattr(
        "custom_components.fitage.er.async_get", lambda unused_hass: registry
    )
    monkeypatch.setattr(
        "custom_components.fitage.er.async_entries_for_config_entry",
        lambda unused_registry, unused_entry_id: registry.entries.copy(),
    )

    assert not await async_migrate_entry(hass, entry)
    assert entry.minor_version == 1
    assert registry.update_calls == []
